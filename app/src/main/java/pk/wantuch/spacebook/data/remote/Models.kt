package pk.wantuch.spacebook.data.remote

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject

@Serializable
data class UserDto(
    val id: Int,
    val name: String = "",
    @SerialName("father_name") val fatherName: String = "",
    @SerialName("user_type") val userType: String = "student",
    val whatsapp: String = "",
    @SerialName("created_at") val createdAt: String = "",
)

@Serializable
data class DeviceDto(val id: String, val token: String)

@Serializable
data class AuthResponse(
    val ok: Boolean = false,
    val user: UserDto? = null,
    val device: DeviceDto? = null,
    val error: String? = null,
)

@Serializable
data class LoginBody(
    val whatsapp: String,
    val password: String,
    @SerialName("want_device") val wantDevice: Boolean = true,
    @SerialName("device_name") val deviceName: String = "SpaceBook Android",
)

@Serializable
data class RegisterBody(
    val name: String,
    @SerialName("father_name") val fatherName: String,
    @SerialName("user_type") val userType: String,
    val whatsapp: String,
    val password: String,
    @SerialName("want_device") val wantDevice: Boolean = true,
    @SerialName("device_name") val deviceName: String = "SpaceBook Android",
)

/** A POST with nothing to say; the server only needs to see JSON. */
@Serializable
class EmptyBody

@Serializable
data class OkResponse(val ok: Boolean = false, val error: String? = null)

/** content/app_catalog.json, generated by tools/build/make_app_catalog.js */
@Serializable
data class Catalog(val schema: String = "", val classes: List<ClassDto> = emptyList()) {
    fun cls(id: String) = classes.firstOrNull { it.id == id }
    fun subject(id: String) = classes.firstNotNullOfOrNull { c -> c.subjects.firstOrNull { it.id == id } }
    fun classOf(subjectId: String) = classes.firstOrNull { c -> c.subjects.any { it.id == subjectId } }
}

@Serializable
data class ClassDto(val id: String, val name: String, val subjects: List<SubjectDto> = emptyList())

@Serializable
data class SubjectDto(
    val id: String,
    val name: String,
    val ur: String = "",
    val emoji: String = "📘",
    val chapters: List<ChapterDto> = emptyList(),
)

/** t = title, o = the web call that opens the chapter once its subject is open, n = exercise items */
@Serializable
data class ChapterDto(val t: String, val o: String = "", val n: Int = 0)

@Serializable
data class SyncEventDto(
    val eventId: String,
    val type: String,
    val payload: JsonElement,
    val clientTs: Long,
    val schema: Int = 1,
)

@Serializable
data class SyncPushBody(val events: List<SyncEventDto>)

@Serializable
data class RejectedDto(val eventId: String, val code: String = "")

@Serializable
data class SyncPushResponse(
    val ok: Boolean = false,
    val accepted: List<String> = emptyList(),
    val rejected: List<RejectedDto> = emptyList(),
    val cursor: Long = 0,
    val coins: Int = 0,
    val error: String? = null,
)

@Serializable
data class PullResponse(
    val ok: Boolean = false,
    val cursor: Long = 0,
    val more: Boolean = false,
    val coins: Int = 0,
    val progress: JsonObject = JsonObject(emptyMap()),
    val plans: List<JsonObject> = emptyList(),
)

@Serializable
data class EntitlementsDto(
    val ok: Boolean = true,
    val plan: String = "free",
    val signedIn: Boolean = false,
    val unlocked: Boolean = true,
    /** "all" or a list; kept as JSON because the server may send either */
    val classes: JsonElement? = null,
    val features: Map<String, Boolean> = emptyMap(),
    val version: Int = 1,
)
