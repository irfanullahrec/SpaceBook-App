object Class5CurriculumRepository {

    fun stagesFor(book: Class5BookType): List<Class4StageData> = when (book) {
        Class5BookType.ENGLISH -> englishStages
        Class5BookType.MATHS -> mathsStages
        Class5BookType.SCIENCE -> scienceStages
        Class5BookType.ISLAMIAT -> Class5IslamiatSocialData.islamiatStages
        Class5BookType.PASHTO -> Class5PashtoUrduData.pashtoStages
        Class5BookType.SOCIAL_STUDY -> Class5IslamiatSocialData.socialStages
        Class5BookType.URDU -> Class5PashtoUrduData.urduStages
    }

    private val colors = listOf(
        Color(0xFF2563EB), Color(0xFF059669), Color(0xFF7C3AED), Color(0xFFD97706)
    )

    private fun unitStage(
        id: Int,
        unitLabel: String,
        pageRange: String,
        titleEn: String,
        titleUr: String,
        titlePs: String,
        summaryEn: String,
        summaryUr: String,
        summaryPs: String,
        c1: Triple<String, String, String>,
        c2: Triple<String, String, String>,
        c3: Triple<String, String, String>,
        c4: Triple<String, String, String>,
        q1En: String,
        q1Ur: String,
        q1Ps: String,
        q1Badge: String,
        q1Options: List<String>,
        q2En: String? = null,
        q2Ur: String? = null,
        q2Ps: String? = null,
        q2Badge: String? = null,
        q2Options: List<String>? = null
    ): Class4StageData {
        val quizList = mutableListOf(
            NazeraQuizQuestion(q1En, q1Ur, q1Ps, q1Badge, q1Options, 0)
        )
        if (q2En != null && q2Ur != null && q2Ps != null && q2Badge != null && q2Options != null) {
            quizList.add(NazeraQuizQuestion(q2En, q2Ur, q2Ps, q2Badge, q2Options, 0))
        }
        return Class4StageData(
            id = id,
            unitLabel = unitLabel,
            pageRange = pageRange,
            titleEn = titleEn,
            titleUr = titleUr,
            titlePs = titlePs,
            summaryEn = summaryEn,
            summaryUr = summaryUr,
            summaryPs = summaryPs,
            gamePromptEn = "Match each concept of $unitLabel with its correct answer!",
            gamePromptUr = "$unitLabel کے تصورات کو درست جواب سے ملائیں!",
            gamePromptPs = "د $unitLabel مفاهیم له سم ځواب سره وصل کړئ!",
            cards = listOf(
                Class4ConceptCard(c1.first, c1.second, c1.third, c1.second, c1.third, colors[0]),
                Class4ConceptCard(c2.first, c2.second, c2.third, c2.second, c2.third, colors[1]),
                Class4ConceptCard(c3.first, c3.second, c3.third, c3.second, c3.third, colors[2]),
                Class4ConceptCard(c4.first, c4.second, c4.third, c4.second, c4.third, colors[3])
            ),
            quizzes = quizList
        )
    }

