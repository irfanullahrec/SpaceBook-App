  function logAnswer(trackId, m, correct, ms) {
    const d = db();
    const r = d.q[m.i] || [0, 0, 0, 0, 0];
    r[0]++; if (correct) r[1]++; r[2] = Date.now(); r[3] = correct ? 1 : 0; r[4] += Math.round(ms);
    d.q[m.i] = r;
    const today = dayKey();
    for (const t of [trackId, 'all']) {
      const days = d.days[t] || (d.days[t] = {});
      const x = days[today] || (days[today] = [0, 0, 0]);
      x[0] += Math.round(Math.min(ms, 5 * 60000)); x[1]++; if (correct) x[2]++;
    }
    save();
    if (v2()) emit('tp.answer', { mcqId: m.i, track: trackId, day: today, correct: !!correct, ms: Math.round(ms), ts: Date.now() });
    // home "My Stats" counters
    try {
      if (typeof getStudyStats === 'function' && typeof saveStudyStats === 'function') {
        const st = getStudyStats();
        st.studiedQuestions = (st.studiedQuestions || 0) + 1;
        if (correct) st.correctAnswers = (st.correctAnswers || 0) + 1; else st.incorrectAnswers = (st.incorrectAnswers || 0) + 1;
        st.todayQuestions = (st.todayQuestions || 0) + 1;
        st.todayMinutes = Math.round(((d.days.all[today] || [0])[0]) / 60000);
        delete st.accuracyRate;
        saveStudyStats(st);
      }
    } catch (e) { /* home stats are optional */ }
  }
