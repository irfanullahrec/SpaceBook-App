  function startRun(mode, qs, opts) {
    const old = db().run;
    if (old && !(S.run && S.run.id === old.id)) {
      const sm = runSummary(old);
      if (!confirm(`You have an unfinished ${old.mode === 'mock' ? 'mock test' : 'practice'} (MCQ ${sm.at} of ${sm.total}). Start a new one and drop it?`)) return;
    }
    S.run = {
      mode, qs, opts: opts || {}, i: 0, answers: qs.map(() => null), times: qs.map(() => 0), shown: qs.map(() => false),
      started: performance.now(), qStart: performance.now(), lang: 'en', finished: false, id: 's' + Date.now().toString(36), startedAt: Date.now()
    };
    stopTimer();
    timerId = setInterval(tick, 250);
    persistRun();
    renderRun();
  }

  async function resume() {
    const run = db().run;
    if (!run) return;
    if (!S.B || S.track !== run.track) { await open(run.track); }
    const qs = run.ids.map(id => S.B.byId.get(id)).filter(Boolean);
    if (!qs.length) { clearRun(); render(); return; }
    const keep = run.ids.map((id, k) => S.B.byId.get(id) ? k : -1).filter(k => k >= 0);
    stopTimer();
    S.run = {
      mode: run.mode, qs, opts: run.opts || {}, i: Math.min(keep.indexOf(run.i) >= 0 ? keep.indexOf(run.i) : 0, qs.length - 1),
      answers: keep.map(k => run.answers[k]), times: keep.map(k => run.times[k] || 0), shown: qs.map(() => false),
      started: performance.now() - (run.elapsed || 0), qStart: performance.now(), lang: run.lang || 'en', finished: false, id: run.id, startedAt: run.startedAt
    };
    // a practice MCQ already answered: show its answer, the student presses Next
    timerId = setInterval(tick, 250);
    renderRun();
  }
