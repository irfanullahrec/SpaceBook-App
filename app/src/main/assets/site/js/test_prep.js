  // ── learning ladder: climb from Easy (bottom) to Expert (top) ───────────
  // A level is "done" when at least 20 of its MCQs (or all, if fewer) are answered
  // and 80% of them were right the last time.
  function ladderInfo(sel) {
    const d = db();
    const rungs = [1, 2, 3, 4, 5].map(l => {
      const pool = sel.filter(m => m.l === l);
      let seen = 0, right = 0;
      pool.forEach(m => { const r = d.q[m.i]; if (r) { seen++; if (r[3]) right++; } });
      const need = Math.min(20, pool.length);
      const acc = seen ? Math.round((right / seen) * 100) : 0;
      return { l, total: pool.length, seen, right, acc, done: pool.length > 0 && seen >= need && acc >= 80 };
    });
    const here = rungs.find(r => r.total && !r.done);
    return { rungs, here: here ? here.l : null };
  }
