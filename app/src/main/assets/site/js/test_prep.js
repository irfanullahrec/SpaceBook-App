  function answer(oi) {
    const r = S.run;
    if (!r || r.finished) return;
    const m = r.qs[r.i];
    if (r.mode === 'practice') {
      if (r.answers[r.i] != null) return;
      commitTime();
      r.answers[r.i] = oi;
      logAnswer(S.track, m, oi === m.a, r.times[r.i]);
      persistRun();
      renderRun();
      if (oi >= 0 && window.SBMcq && SBMcq.toast) SBMcq.toast(oi === m.a, 'en');
    } else {
      r.answers[r.i] = oi;
      persistRun();
      renderRun();
    }
  }
  function next() {
    const r = S.run;
    if (!r) return;
    if (r.i >= r.qs.length - 1) { finishRun(); return; }
    r.i++; r.qStart = performance.now();
    persistRun();
    renderRun();
  }
  function jump(i) {
    const r = S.run;
    if (!r || i < 0 || i >= r.qs.length) return;
    commitTime();
    r.i = i;
    persistRun();
    renderRun();
  }

  function finishRun(timeUp) {
    const r = S.run;
    if (!r || r.finished) return;
    if (r.mode === 'mock') {
      const unanswered = r.answers.filter(a => a == null).length;
      if (!timeUp && unanswered && !confirm(`${unanswered} MCQ${unanswered > 1 ? 's are' : ' is'} not answered. Submit the test anyway?`)) return;
      commitTime();
      r.qs.forEach((m, i) => { if (r.answers[i] != null) logAnswer(S.track, m, r.answers[i] === m.a, r.times[i]); });
    } else if (r.answers[r.i] == null) {
      r.times[r.i] += elapsedQ();
    }
    r.finished = true;
    r.timeUp = !!timeUp;
    stopTimer();
    clearRun();
    // keep only answered questions for a practice session
    const idx = r.qs.map((_, i) => i).filter(i => r.mode === 'mock' || r.answers[i] != null);
    if (idx.length) {
      const secsAgg = {}, lv = {};
      let c = 0, ms = 0;
      idx.forEach(i => {
        const m = r.qs[i], ok = r.answers[i] === m.a;
        if (ok) c++;
        ms += r.times[i];
        const sec = S.sections.find(s => s.cats.includes(m.k));
        const sn = sec ? sec.name : (CAT_NAME[m.k] || m.k);
        (secsAgg[sn] = secsAgg[sn] || [0, 0])[0]++; if (ok) secsAgg[sn][1]++;
        (lv[m.l] = lv[m.l] || [0, 0])[0]++; if (ok) lv[m.l][1]++;
      });
      const d = db();
      const sessRec = { id: r.id, track: S.track, mode: r.mode, ts: Date.now(), n: idx.length, c, ms: Math.round(ms),
        items: idx.map(i => [r.qs[i].i, r.answers[i] == null ? null : r.answers[i], Math.round(r.times[i])]), secs: secsAgg, lv };
      d.sessions.push(sessRec);
      save();
      if (v2()) emit('tp.session', { session: sessRec });
    }
    renderRun();
  }

