  // weighted pick across sections
  function pickQuestions(pool, count, opts) {
    const d = db();
    const st = opts || {};
    let items = pool;
    if (st.include === 'unseen') items = items.filter(m => !d.q[m.i]);
    if (st.include === 'wrong') items = items.filter(m => d.q[m.i] && !d.q[m.i][3]);
    if (st.level && /^[1-5]$/.test(st.level)) items = items.filter(m => m.l === +st.level);
    if (!items.length) return [];
    // group by section, take shares by weight
    const groups = S.sections.map((sec, i) => ({ w: sec.w, on: st.secs ? st.secs[i] : true, list: [] }));
    const placed = new Set();
    items.forEach(m => {
      const gi = S.sections.findIndex((sec, i) => groups[i].on && sec.cats.includes(m.k));
      if (gi >= 0 && !placed.has(m.i)) { placed.add(m.i); groups[gi].list.push(m); }
    });
    const live = groups.filter(g => g.list.length);
    const wsum = live.reduce((s, g) => s + g.w, 0) || 1;
    let picked = [];
    live.forEach(g => {
      // prefer unseen, then wrong, then the rest — so practice keeps moving to new MCQs
      let ranked = shuffle(g.list.slice()).sort((a, b) => rank(a) - rank(b));
      // all levels: deal the MCQs out level by level (Class 1–3, 4–5, 6–8 …) so every
      // session climbs from easy to difficult instead of drawing only from the largest level
      if (!/^[1-5]$/.test(String(st.level))) {
        const byLv = [1, 2, 3, 4, 5].map(l => ranked.filter(m => m.l === l)).filter(x => x.length);
        const dealt = [];
        for (let k = 0; dealt.length < ranked.length; k++) byLv.forEach(x => { if (x[k]) dealt.push(x[k]); });
        ranked = dealt;
      }
      g.take = Math.min(g.list.length, Math.max(1, Math.round((g.w / wsum) * count)));
      picked.push(...ranked.slice(0, g.take));
      g.rest = ranked.slice(g.take);
    });
    // fill to count from what is left
    const rest = shuffle([].concat(...live.map(g => g.rest)));
    while (picked.length < count && rest.length) picked.push(rest.shift());
    if (picked.length > count) picked = shuffle(picked).slice(0, count);
    if (st.level === 'mix') shuffle(picked);
    else picked.sort((a, b) => a.l - b.l || a.c - b.c || Math.random() - 0.5);
    return picked;
    function rank(m) { const r = d.q[m.i]; if (!r) return 0; if (!r[3]) return 1; return 2 + r[1]; }
  }

