  function mistakesList() {
    const d = db();
    return trackPool().filter(m => d.q[m.i] && !d.q[m.i][3]).sort((a, b) => d.q[b.i][2] - d.q[a.i][2]);
  }
  function mistakesHtml() {
    const list = mistakesList();
    if (!list.length) return '<div class="tp-card tp-empty">🎉 No mistakes waiting. Every MCQ you answered last time was correct. Wrong answers appear here until you get them right.</div>';
    const d = db();
    return `<div class="tp-card">
      <div class="tp-row-between"><div class="tp-card-title">❌ ${fmt(list.length)} MCQs to fix</div>
        <button type="button" class="tp-start tp-start-inline" onclick="SBTestPrep.practiseMistakes()">🔁 Practise ${Math.min(list.length, 30)} of them now</button></div>
      <div class="tp-note">An MCQ leaves this list when you answer it correctly.</div>
      <div class="tp-review">${list.slice(0, 200).map(m => {
        const r = d.q[m.i];
        return `<div class="tp-rv bad"><div class="tp-rv-h"><small>${esc((S.B.subjects[m.s] || {}).name || '')} · Class ${m.c} · tried ${r[0]}× · right ${r[1]}× · last ${new Date(r[2]).toLocaleDateString()}</small></div>
          <div class="tp-rv-q" dir="${isRtl(m.q) ? 'rtl' : 'ltr'}">${rich(m.q)}</div>
          <div class="tp-rv-o">${m.o.map((o, oi) => `<span class="${oi === m.a ? 'c' : ''}" dir="${isRtl(o) ? 'rtl' : 'ltr'}">${m.tf ? '' : 'ABCD'[oi] + '. '}${rich(o)}</span>`).join('')}</div></div>`;
      }).join('')}</div></div>`;
  }
  function practiseMistakes() {
    const list = shuffle(mistakesList().slice()).slice(0, 30).sort((a, b) => a.l - b.l);
    if (list.length) startRun('practice', list, {});
  }

  // ── history ─────────────────────────────────────────────────────────────
  function historyHtml() {
    const sess = db().sessions.filter(s => s.track === S.track).slice().reverse();
    if (!sess.length) return '<div class="tp-card tp-empty">📜 No sessions yet. Start a practice or mock test and every session will be listed here with its score, accuracy and speed.</div>';
    return `<div class="tp-card"><div class="tp-card-title">📜 ${fmt(sess.length)} sessions</div>
      <div class="tp-table-wrap"><table class="tp-table">
        <thead><tr><th>Date</th><th>Mode</th><th>MCQs</th><th>Score</th><th>Accuracy</th><th>Speed</th><th>Time</th><th></th></tr></thead>
        <tbody>${sess.map(s => `<tr onclick="SBTestPrep.review('${s.id}')">
          <td>${new Date(s.ts).toLocaleString([], { dateStyle: 'medium', timeStyle: 'short' })}</td>
          <td>${s.mode === 'mock' ? '⏱️ Mock' : '🎯 Practice'}</td><td>${s.n}</td><td>${s.c}/${s.n}</td>
          <td><span class="tp-acc" style="--a:${pct(s.c, s.n) >= 60 ? '#059669' : pct(s.c, s.n) >= 40 ? '#d97706' : '#e11d48'}">${pct(s.c, s.n)}%</span></td>
          <td>${s.n ? secs(s.ms / s.n).toFixed(1) : 0} s</td><td>${mmss(s.ms)}</td><td class="tp-go">Review ›</td></tr>`).join('')}</tbody>
      </table></div></div>`;
  }
  function reviewHtml(id) {
    const s = db().sessions.find(x => x.id === id);
    if (!s) return historyHtml();
    return `<div class="tp-row-between tp-mb"><button type="button" class="tp-nav" onclick="SBTestPrep.review(null)">‹ All sessions</button>
      <div class="tp-review-title">${s.mode === 'mock' ? '⏱️ Mock test' : '🎯 Practice'} · ${new Date(s.ts).toLocaleString()} · <b>${s.c}/${s.n} (${pct(s.c, s.n)}%)</b> · ${mmss(s.ms)}</div></div>
      ${breakdownHtml(s)}${reviewListHtml(s.items || [])}`;
  }

  // ── reset the statistics of this test plan (track) ─────────────────────────
  function resetStats() {
    const d = db(), t = S.track, now = Date.now();
    if (!confirm(`Reset all statistics of "${S.info.title}"? Your answers, history, mistakes and daily study time for this test will be cleared. This cannot be undone.`)) return;
    const ids = []; (S.pools || []).forEach(p => p.forEach(m => ids.push(m.i)));
    ids.forEach(id => { if (d.q[id]) { d.rid[id] = now; delete d.q[id]; } });
    const tdays = d.days[t] || {};
    if (d.days.all) Object.keys(tdays).forEach(k => { const a = d.days.all[k]; if (!a) return; const v = tdays[k]; a[0] = Math.max(0, a[0] - v[0]); a[1] = Math.max(0, a[1] - v[1]); a[2] = Math.max(0, a[2] - v[2]); });
    d.days[t] = {};
    d.sessions = d.sessions.filter(x => x.track !== t);
    d.resets[t] = now;
    if (d.run && d.run.track === t) { d.run = null; d.runClearedAt = now; }
    S.reviewSession = null; S.tab = 'stats';
    save(); render();
  }

  // ── stats ───────────────────────────────────────────────────────────────
  function statsHtml() {
    const d = db();
    const days = d.days[S.track] || {};
    const list = [];
    for (let k = 13; k >= 0; k--) { const x = new Date(); x.setDate(x.getDate() - k); const key = dayKey(x); list.push({ key, x, v: days[key] || [0, 0, 0] }); }
    const sum = arr => arr.reduce((a, o) => [a[0] + o.v[0], a[1] + o.v[1], a[2] + o.v[2]], [0, 0, 0]);
    const thisW = sum(list.slice(7)), lastW = sum(list.slice(0, 7));
    const trend = (cur, prev, unit, better, fmtv) => {
      const diff = cur - prev;
      const up = diff > 0, same = Math.abs(diff) < 1e-9 || String(fmtv(Math.abs(diff))).replace(/[0.,]/g, '') === '';
      const good = same ? null : (better === 'up' ? up : !up);
      return `<span class="tp-trend ${same ? '' : good ? 'good' : 'bad'}">${same ? '＝ same as last week' : (up ? '▲ ' : '▼ ') + fmtv(Math.abs(diff)) + unit + ' vs last week'}</span>`;
    };
    const accT = pct(thisW[2], thisW[1]), accL = pct(lastW[2], lastW[1]);
    const spdT = thisW[1] ? thisW[0] / thisW[1] / 1000 : 0, spdL = lastW[1] ? lastW[0] / lastW[1] / 1000 : 0;
    const maxMin = Math.max(5, ...list.map(o => o.v[0] / 60000));
    const chart = `<div class="tp-chart">${list.map(o => {
      const min = o.v[0] / 60000, acc = pct(o.v[2], o.v[1]);
      const isToday = o.key === dayKey();
      return `<div class="tp-col ${isToday ? 'today' : ''}" title="${o.x.toDateString()}: ${min.toFixed(1)} min · ${o.v[1]} MCQs · ${acc}% correct">
        <span class="tp-col-acc">${o.v[1] ? acc + '%' : ''}</span>
        <div class="tp-col-bar"><div style="height:${(min / maxMin) * 100}%"></div></div>
        <span class="tp-col-min">${o.v[1] ? Math.round(min) + 'm' : '·'}</span>
        <span class="tp-col-day">${o.x.toLocaleDateString([], { weekday: 'short' }).slice(0, 2)} ${o.x.getDate()}</span></div>`;
    }).join('')}</div>`;

    // all-time by section and level for this track
    const secAgg = {}, lvAgg = {};
    d.sessions.filter(s => s.track === S.track).forEach(s => {
      for (const [k, [n, c]] of Object.entries(s.secs || {})) { const a = secAgg[k] || (secAgg[k] = [0, 0]); a[0] += n; a[1] += c; }
      for (const [k, [n, c]] of Object.entries(s.lv || {})) { const a = lvAgg[k] || (lvAgg[k] = [0, 0]); a[0] += n; a[1] += c; }
    });
    // coverage per section
    const cover = S.sections.map((sec, i) => { const pool = S.pools[i]; const seen = pool.filter(m => d.q[m.i]).length; return [sec.name, seen, pool.length]; });
    // accuracy over the last 10 sessions
    const last = d.sessions.filter(s => s.track === S.track).slice(-10);
    const spark = last.length > 1 ? sparkline(last.map(s => pct(s.c, s.n))) : '';
    return `
      <div class="tp-row-between tp-mb"><span class="tp-note">Statistics of ${esc(S.info.title)}</span><button type="button" class="tp-nav" onclick="SBTestPrep.resetStats()" title="Clear answers, history, mistakes and daily time of this test">🗑️ Reset statistics</button></div>
      <div class="tp-trends">
        <div class="tp-trend-card"><div class="tp-kpi-l">Study time this week</div><div class="tp-kpi-v">${Math.round(thisW[0] / 60000)} min</div>${trend(thisW[0] / 60000, lastW[0] / 60000, ' min', 'up', v => Math.round(v))}</div>
        <div class="tp-trend-card"><div class="tp-kpi-l">MCQs this week</div><div class="tp-kpi-v">${fmt(thisW[1])}</div>${trend(thisW[1], lastW[1], '', 'up', v => fmt(v))}</div>
        <div class="tp-trend-card"><div class="tp-kpi-l">Accuracy this week</div><div class="tp-kpi-v">${thisW[1] ? accT + '%' : '—'}</div>${thisW[1] && lastW[1] ? trend(accT, accL, ' pts', 'up', v => v.toFixed(1)) : '<span class="tp-trend">needs two weeks of practice</span>'}</div>
        <div class="tp-trend-card"><div class="tp-kpi-l">Speed this week</div><div class="tp-kpi-v">${thisW[1] ? spdT.toFixed(1) + ' s' : '—'}</div>${thisW[1] && lastW[1] ? trend(spdT, spdL, ' s', 'down', v => v.toFixed(1)) : '<span class="tp-trend">seconds per MCQ (lower is faster)</span>'}</div>
      </div>
      <div class="tp-card">
        <div class="tp-row-between"><div class="tp-card-title">📅 Daily study time — last 14 days</div><div class="tp-note">bar = minutes studied · top = % correct that day</div></div>
        ${chart}
      </div>
      <div class="tp-grid2">
        <div class="tp-card"><div class="tp-card-title">🎯 Accuracy by section</div>${Object.entries(secAgg).map(([k, [n, c]]) => barRow(k, c, n)).join('') || '<div class="tp-note">Practise to see your strong and weak sections.</div>'}</div>
        <div class="tp-card"><div class="tp-card-title">📈 Accuracy by level (easy → difficult)</div>${[1, 2, 3, 4, 5].filter(l => lvAgg[l]).map(l => barRow(LEVELS[l].name + ' · ' + LEVELS[l].cls, lvAgg[l][1], lvAgg[l][0], LEVELS[l].color)).join('') || '<div class="tp-note">No answers yet.</div>'}</div>
        <div class="tp-card"><div class="tp-card-title">🗺️ Syllabus covered</div>${cover.map(([name, seen, total]) => `<div class="tp-lvl-row"><span>${esc(name)}</span><small>${fmt(seen)}/${fmt(total)}</small><div class="tp-bar"><div style="width:${total ? (seen / total) * 100 : 0}%"></div></div><b>${total ? Math.round((seen / total) * 100) : 0}%</b></div>`).join('')}</div>
        <div class="tp-card"><div class="tp-card-title">📉 Accuracy — last ${last.length} sessions</div>${spark || '<div class="tp-note">Finish two or more sessions to see your trend.</div>'}</div>
      </div>`;
  }
  function sparkline(vals) {
    const w = 320, h = 90, n = vals.length;
    const pts = vals.map((v, i) => [10 + (i * (w - 20)) / (n - 1), h - 10 - (v / 100) * (h - 20)]);
    return `<svg class="tp-spark" viewBox="0 0 ${w} ${h}" role="img" aria-label="Accuracy trend">
      <line x1="10" x2="${w - 10}" y1="${h - 10 - 0.6 * (h - 20)}" y2="${h - 10 - 0.6 * (h - 20)}" class="tp-spark-ref"/>
      <polyline points="${pts.map(p => p.join(',')).join(' ')}" class="tp-spark-line"/>
      ${pts.map((p, i) => `<circle cx="${p[0]}" cy="${p[1]}" r="3.5" class="tp-spark-dot"><title>${vals[i]}%</title></circle>`).join('')}
    </svg><div class="tp-note">Dashed line = 60%.</div>`;
  }

  // ── keyboard ────────────────────────────────────────────────────────────
  document.addEventListener('keydown', e => {
    const r = S.run;
    if (!r || r.finished || !document.querySelector('.tp-running')) return;
    if (e.target && /input|textarea|select/i.test(e.target.tagName)) return;
    const k = e.key.toLowerCase();
    const m = r.qs[r.i];
    let oi = -2;
    if (/^[1-4]$/.test(k)) oi = +k - 1;
    else if (/^[a-d]$/.test(k)) oi = 'abcd'.indexOf(k);
    if (oi >= 0 && oi < m.o.length) { e.preventDefault(); answer(oi); return; }
    if (k === 'enter') {
      e.preventDefault();
      if (r.mode === 'practice' && r.answers[r.i] != null) next();
      else if (r.mode === 'mock') jump(r.i + 1);
    }
    if (r.mode === 'mock' && k === 'arrowright') jump(r.i + 1);
    if (r.mode === 'mock' && k === 'arrowleft') jump(r.i - 1);
  });

