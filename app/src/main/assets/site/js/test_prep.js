  function tick() {
    const r = S.run;
    if (!r || r.finished) { stopTimer(); return; }
    const el = document.getElementById('tpClock');
    if (!el) { persistRun(); stopTimer(); return; }
    if (r.mode === 'mock') {
      const left = r.opts.total - (performance.now() - r.started);
      el.textContent = '⏳ ' + mmss(left);
      el.classList.toggle('tp-warn', left < 60000);
      if (left <= 0) finishRun(true);
    } else {
      const spent = r.times[r.i] + (r.answers[r.i] == null ? elapsedQ() : 0);
      if (r.opts.qtime) {
        const left = r.opts.qtime * 1000 - spent;
        el.textContent = '⏳ ' + mmss(left);
        el.classList.toggle('tp-warn', left < 10000);
        if (left <= 0 && r.answers[r.i] == null) answer(-1);
      } else el.textContent = '⏱️ ' + mmss(spent);
    }
  }

