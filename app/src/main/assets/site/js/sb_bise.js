  const fmtClock = dr => { const left = Math.max(0, dr.deadline - Date.now()); const m = Math.floor(left / 60000), sec = Math.floor(left / 1000) % 60; return (m < 10 ? '0' : '') + m + ':' + (sec < 10 ? '0' : '') + sec; };
  let clockTimer = null;
  function startClock() {
    stopClock();
    clockTimer = setInterval(() => {
      const dr = S.drill;
      if (!dr || dr.finished || !document.getElementById('biseClock')) { stopClock(); return; }
      document.getElementById('biseClock').textContent = fmtClock(dr);
      if (Date.now() >= dr.deadline) endDrill();
    }, 500);
  }
  function stopClock() { if (clockTimer) { clearInterval(clockTimer); clockTimer = null; } }

  async function startDrill(sid) {
    const s = D.subjects[sid];
    const n = s.pattern ? s.pattern.A.n : 12, min = s.pattern && s.pattern.A.min ? s.pattern.A.min : 20;
    S.drill = { sid, loading: true };
    S.tab = 'practice'; render();
    let B;
    try { B = await loadBank(); } catch (e) { S.drill = { sid, error: 'The MCQ bank could not be loaded. Please reload the page.' }; render(); return; }
    const pool = (B.mcqs || []).filter(m => m.s === sid && m.o && m.o.length >= 2 && m.a != null);
    if (pool.length < 4) { S.drill = { sid, error: 'This subject has too few multiple-choice questions with a printed answer key in the books yet (' + pool.length + '). Use Tests Preps or Papers for other subjects.' }; render(); return; }
    const pick = pool.slice().sort(() => Math.random() - 0.5).slice(0, n);
    S.drill = { sid, qs: pick, ans: pick.map(() => null), start: Date.now(), deadline: Date.now() + min * 60000, finished: false };
    render(); startClock(); window.scrollTo(0, 0);
  }
  function endDrill() {
    const dr = S.drill;
    if (!dr || dr.finished) return;
    dr.finished = true; stopClock();
    const c = dr.qs.reduce((n, m, i) => n + (dr.ans[i] === m.a ? 1 : 0), 0);
    db().drills.push({ sid: dr.sid, ts: Date.now(), n: dr.qs.length, c, ms: Math.min(Date.now(), dr.deadline) - dr.start });
    if (db().drills.length > 200) db().drills.splice(0, db().drills.length - 200);
    save(); render(); window.scrollTo(0, 0);
  }

