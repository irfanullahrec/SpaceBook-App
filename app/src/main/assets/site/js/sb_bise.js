  async function open(sid, tab, chapter, from) {
    setView();
    const el = root();
    if (!el) return;
    if (from !== undefined) S.from = from;
    el.innerHTML = '<div class="bise-root"><div class="bise-loading"><span class="bise-spin"></span> Loading the BISE Swat Board centre…</div></div>';
    window.scrollTo(0, 0);
    try { await loadData(); } catch (e) {
      el.querySelector('.bise-loading').textContent = 'The BISE Swat data could not be loaded. Please reload the page.';
      return;
    }
    if (!sid || !D.subjects[sid]) {
      const first = sid && /^cls(\d+)/.exec(sid);
      const cls = first ? +first[1] : S.cls;
      const list = subjectsOf(cls);
      sid = (S.sid && D.subjects[S.sid] && D.subjects[S.sid].cls === cls) ? S.sid : (list[0] && list[0].id);
    }
    S.sid = sid; S.cls = D.subjects[sid].cls;
    if (tab) S.tab = tab;
    if (chapter != null) S.openCh = chapter;
    S.filter = ''; S.drill = (S.tab === 'practice') ? S.drill : null;
    render();
  }

